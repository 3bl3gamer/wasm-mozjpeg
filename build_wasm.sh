#!/bin/bash
set -e

help=""
debug=""
no_patch=""
for i in "$@"; do
    case $i in
        -h*) help="${i#*=}";;
        --help*) help="${i#*=}";;
        --debug*) debug="${i#*=}";;
        --no-patch*) no_patch="${i#*=}";;
    esac
done

if [ "$help" != "" ]; then
  echo "usage: $0 [--debug] [--no-patch]"
  echo "  --debug     preserve wasm debug information and generate sourcemap"
  echo "  --no-patch  do not re-apply patch file (faster rebuild)"
  echo "  --help, -h  show this info"
  exit 2
fi


# Loops unrolling gives no speedup in Chome and about 1-2% speedup in FF,
# but increases .wasm size by 6%. So disabling it.
COMMON_MAKE_ARGS="-fno-unroll-loops"
FINAL_MAKE_ARGS=""
if [ "$debug" != "" ]; then
  COMMON_MAKE_ARGS="$COMMON_MAKE_ARGS -g"
  FINAL_MAKE_ARGS="$FINAL_MAKE_ARGS -gsource-map --source-map-base=./"
fi

echo ""
echo " === Building MozJPEG === "
echo ""

cd mozjpeg

if [ "$no_patch" == "" ]; then
  git checkout .
  git apply ../mozjpeg_shrink.patch
fi

# FACEPALM
# "type":"module" in root directory *silently* breaks something
# in emscripten's types size detection (UNSIGNED_LONG etc.)
# and they all change to 1 byte.
# Affects CMakeLists.txt and jcphuff.c (#if SIZEOF_SIZE_T == 4 and others).
echo '{"type":"commonjs"}' > package.json

emcmake cmake -G"Unix Makefiles" \
  -DCMAKE_C_COMPILER=emcc \
  -DCMAKE_SIZEOF_VOID_P=4 \
  -DWITH_ARITH_ENC=0 \
  -DWITH_SIMD=0 \
  -DBUILD_SHARED_LIBS=0 \
  -DWITH_TURBOJPEG=0 \
  -DCMAKE_C_FLAGS="-DNO_GETENV=1 $COMMON_MAKE_ARGS" \
  .

emmake make -j 4 jpeg-static

cd -


echo ""
echo " === Building mozjpeg.wasm === "
echo ""

emcc \
  -s STRICT=1 \
  -s STACK_SIZE=1MB \
  -s INITIAL_MEMORY=2MB \
  -s STANDALONE_WASM=1 \
  -s SUPPORT_LONGJMP=0 `#1(default) will add "emscripten_stack_get_current" and "_emscripten_stack_restore" to exports` \
  -s ALLOW_MEMORY_GROWTH=1 \
  -s ERROR_ON_UNDEFINED_SYMBOLS=0 \
  -Wall -O3 -flto -Wl,--lto-O3,--no-entry \
  -nostdlib \
  $COMMON_MAKE_ARGS \
  $FINAL_MAKE_ARGS \
  -I mozjpeg \
  -o mozjpeg.wasm \
  mozjpeg.c custom_libc.c mozjpeg/libjpeg.a mozjpeg/rdswitch.c


echo ""
echo " === Generating const.js === "
echo ""

echo '#include <emscripten.h>' > temp.c
echo '#include "cdjpeg.h"' >> temp.c
for name in JCS_GRAYSCALE JCS_RGB JCS_YCbCr JCS_CMYK JCS_YCCK JCS_EXT_RGB JCS_EXT_BGR JCS_EXT_RGBA JCS_EXT_BGRA JCS_EXT_ABGR JCS_EXT_ARGB
do
  echo "EMSCRIPTEN_KEEPALIVE const J_COLOR_SPACE _$name = $name;" >> temp.c
done

emcc \
  -s STRICT=1 \
  -s STACK_SIZE=1KB \
  -s INITIAL_MEMORY=64KB \
  -s STANDALONE_WASM=1 \
  -s SUPPORT_LONGJMP=0 \
  -s ALLOW_MEMORY_GROWTH=0 \
  -s ERROR_ON_UNDEFINED_SYMBOLS=1 \
  -I mozjpeg \
  -Wall -O3 -Wl,--no-entry -nostdlib \
  -o temp.wasm temp.c

echo "/**
 * Generated by $0, do not edit
 */" > const.js

node -e "
WebAssembly.instantiate(fs.readFileSync('temp.wasm')).then(({instance:{exports}}) => {
  console.log(
    Object.entries(exports)
      .filter(([name,]) => name.startsWith('_JCS_'))
      .map(([name,exp]) => \`export const \${name.substr(1)} = \${new Uint32Array(exports.memory.buffer, exp.value)[0]}\`)
      .join('\\n')
  )
})" >> const.js

rm temp.c temp.wasm

echo " === Done === "
